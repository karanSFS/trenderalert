import { theme as antdTheme, type ThemeConfig } from "antd";
import type { ThemeMode, ThemeTokens } from "./themes";

/** Maps TrenderAlert tokens onto Ant Design's global and component tokens. */
export function buildAntdTheme(tokens: ThemeTokens, mode: ThemeMode): ThemeConfig {
  const c = tokens.colors;
  const t = tokens.typography;
  const isDark = mode === "dark";
  // Yellow text on light surfaces fails contrast, so "selected" text uses ink in light mode.
  const selectedInk = isDark ? c.primary : c.textPrimary;

  return {
    algorithm: isDark ? antdTheme.darkAlgorithm : antdTheme.defaultAlgorithm,
    token: {
      colorPrimary: c.primary,
      colorPrimaryHover: c.primaryHover,
      colorPrimaryActive: c.primaryActive,
      colorSuccess: c.success,
      colorWarning: c.warning,
      colorError: c.error,
      colorInfo: c.info,
      colorLink: c.accentText,
      colorLinkHover: isDark ? c.primaryHover : c.textPrimary,
      colorBgLayout: c.background,
      colorBgContainer: c.surface,
      colorBgElevated: c.surfaceElevated,
      colorText: c.textPrimary,
      colorTextSecondary: c.textSecondary,
      colorTextTertiary: c.textTertiary,
      colorBorder: c.borderStrong,
      colorBorderSecondary: c.border,
      controlItemBgActive: c.primarySoft,
      controlItemBgActiveHover: c.primarySoft,
      controlOutline: isDark ? "rgba(255, 212, 0, 0.35)" : "rgba(17, 17, 17, 0.18)",
      fontFamily: t.fontFamily,
      fontFamilyCode: t.fontFamilyMono,
      fontSize: t.fontSizeBase,
      fontSizeSM: t.fontSizeSm,
      fontSizeLG: t.fontSizeLg,
      fontSizeHeading1: t.h1,
      fontSizeHeading2: t.h2,
      fontSizeHeading3: t.h3,
      fontSizeHeading4: t.h4,
      lineHeight: t.lineHeight,
      borderRadius: tokens.radii.input,
      borderRadiusLG: tokens.radii.card,
      borderRadiusSM: tokens.radii.tag,
      boxShadow: tokens.shadows.elevated,
      boxShadowSecondary: tokens.shadows.elevated,
      wireframe: false,
    },
    components: {
      Button: {
        primaryColor: c.onPrimary,
        primaryShadow: "none",
        defaultShadow: "none",
        dangerShadow: "none",
        fontWeight: 600,
        borderRadius: tokens.radii.button,
        borderRadiusLG: tokens.radii.button,
        borderRadiusSM: tokens.radii.button - 2,
      },
      Input: {
        activeBorderColor: selectedInk,
        hoverBorderColor: selectedInk,
        activeShadow: `0 0 0 3px ${isDark ? "rgba(255, 212, 0, 0.25)" : "rgba(255, 212, 0, 0.45)"}`,
      },
      Select: {
        activeBorderColor: selectedInk,
        hoverBorderColor: selectedInk,
        optionSelectedColor: c.textPrimary,
      },
      Checkbox: { colorWhite: c.onPrimary },
      Radio: { colorWhite: c.onPrimary, buttonSolidCheckedColor: c.onPrimary },
      DatePicker: { colorTextLightSolid: c.onPrimary },
      Steps: { colorTextLightSolid: c.onPrimary },
      Tabs: {
        inkBarColor: c.primary,
        itemSelectedColor: selectedInk,
        itemActiveColor: selectedInk,
        itemHoverColor: selectedInk,
      },
      Pagination: {
        itemActiveBg: c.primary,
        itemActiveColor: c.onPrimary,
        itemActiveColorHover: c.onPrimary,
        colorPrimary: c.onPrimary,
        colorPrimaryHover: c.onPrimary,
      },
      Layout: {
        bodyBg: c.background,
        headerBg: c.surface,
        siderBg: c.sidebarBackground,
        triggerBg: c.sidebarBackground,
        headerPadding: "0 24px",
      },
      Menu: {
        darkItemBg: c.sidebarBackground,
        darkSubMenuItemBg: c.sidebarBackground,
        darkPopupBg: c.sidebarBackground,
        darkItemColor: c.sidebarText,
        darkItemHoverColor: "#FFFFFF",
        darkItemHoverBg: "rgba(255, 255, 255, 0.06)",
        darkItemSelectedBg: c.sidebarActiveBackground,
        darkItemSelectedColor: c.sidebarActiveText,
        darkGroupTitleColor: c.sidebarTextMuted,
        itemBorderRadius: tokens.radii.button,
        subMenuItemBorderRadius: tokens.radii.button,
        itemMarginInline: 8,
        iconSize: 16,
        collapsedIconSize: 18,
        itemSelectedBg: c.primarySoft,
        itemSelectedColor: c.textPrimary,
      },
      Table: {
        headerBg: c.surfaceMuted,
        headerColor: c.textSecondary,
        rowHoverBg: c.surfaceMuted,
        rowSelectedBg: c.primarySoft,
        rowSelectedHoverBg: c.primarySoft,
        borderColor: c.border,
        headerSplitColor: "transparent",
      },
      Card: { headerFontSize: t.fontSizeLg },
      Tag: { borderRadiusSM: tokens.radii.tag },
      Badge: { colorTextLightSolid: "#FFFFFF" },
      Breadcrumb: {
        lastItemColor: c.textPrimary,
        linkColor: c.textSecondary,
        linkHoverColor: c.textPrimary,
      },
      Segmented: { itemSelectedColor: c.textPrimary },
      Switch: { handleBg: "#FFFFFF" },
      Tooltip: { colorTextLightSolid: "#FFFFFF" },
    },
  };
}
